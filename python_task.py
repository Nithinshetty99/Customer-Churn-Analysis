import pandas as pd
import numpy as np

np.random.seed(42)

n = 200

# Create dataset
data = pd.DataFrame({
    'Customer_ID': np.arange(1, n+1),
    'Age': np.random.randint(18, 60, n),
    'Location': np.random.choice(['Urban', 'Rural', 'Semi-Urban'], n),
    'Monthly_Usage_Hours': np.random.randint(5, 100, n),
    'Subscription_Type': np.random.choice(['Basic', 'Standard', 'Premium'], n),
    'Monthly_Bill': np.random.randint(200, 2000, n),
    'Tenure_Months': np.random.randint(1, 36, n)
})

# Create churn column (0 = Retained, 1 = Churned)
data['Churn'] = np.random.choice([0, 1], n, p=[0.7, 0.3])

# Add realistic churn behavior
# Higher churn for:
# - Low usage
# - High bill
# - Short tenure

condition = (
    (data['Monthly_Usage_Hours'] < 20) |
    (data['Monthly_Bill'] > 1500) |
    (data['Tenure_Months'] < 6)
)

data.loc[condition, 'Churn'] = 1

print(data)
print("\nTotal Records:", len(data))



# 1. Analyze churn vs age, location, usage

# Churn vs Age
# Create age groups
data['Age_Group'] = pd.cut(data['Age'], bins=[18,25,35,45,60])

age_churn = data.groupby('Age_Group')['Churn'].mean().sort_index()
print(age_churn)

# Churn vs Location
location_churn = data.groupby('Location')['Churn'].mean()
print(location_churn)

# Churn vs Monthly Usage
# Create usage groups
data['Usage_Group'] = pd.cut(data['Monthly_Usage_Hours'], bins=[0,20,50,100])

usage_churn = data.groupby('Usage_Group')['Churn'].mean().sort_index()
print(usage_churn)



# 2. Compare churned vs retained customers

churned = data[data['Churn'] == 1]
retained = data[data['Churn'] == 0]

comparison = pd.DataFrame({
    'Churned_Customers': churned.mean(numeric_only=True),
    'Retained_Customers': retained.mean(numeric_only=True)
})

print(comparison)


#  3. Identify patterns

high_risk = data[
    (data['Monthly_Usage_Hours'] < 20) &
    (data['Monthly_Bill'] > 1500) &
    (data['Tenure_Months'] < 6)
]

print("High-risk churn group size:", len(high_risk))


#  4. Churn Rate Calculation

#  Calculate overall churn rate (%)
churn_rate = (data['Churn'].sum() / len(data)) * 100
print("Overall Churn Rate: {:.2f}%".format(churn_rate))



#  5. Churn by Age Group

# Create age groups (18–25, 26–35, etc.)
data['Age_Group'] = pd.cut(
    data['Age'],
    bins=[18, 25, 35, 45, 60],
    labels=['18-25', '26-35', '36-45', '46-60']
)

# Calculate Churn Rate per Age Group
age_churn = data.groupby('Age_Group')['Churn'].mean() * 100
print(age_churn)

# Identify Highest Churn Group
highest_churn_group = age_churn.idxmax()
print("Highest Churn Age Group:", highest_churn_group)



#  6. Churn by Location

# Calculate Churn Rate by Location
# Compare Urban, Rural, Semi-Urban
location_churn = data.groupby('Location')['Churn'].mean() * 100
print(location_churn)



#  7. Churn vs Subscription Type

sub_churn = data.groupby('Subscription_Type')['Churn'].mean() * 100
print(sub_churn)

# Identify Highest Churn Plan
highest_plan = sub_churn.idxmax()
print("Highest Churn Plan:", highest_plan)

# Basic vs Premium Comparison
basic_vs_premium = sub_churn[['Basic', 'Premium']]
print(basic_vs_premium)



#  8. Monthly Usage Impact

# Low usage vs high churn
data['Usage_Group'] = pd.cut(
    data['Monthly_Usage_Hours'],
    bins=[0, 20, 50, 100],
    labels=['Low (0-20)', 'Medium (21-50)', 'High (51-100)']
)


# Find usage threshold where churn increases
usage_churn = data.groupby('Usage_Group')['Churn'].mean() * 100
print(usage_churn)